	/**
	 * Current plugin language code.
	 *
	 * @return string
	 */
	public static function language() {
		$code = (string) VisualPay_Settings::get( 'language', 'en' );
		return array_key_exists( $code, self::languages() ) ? $code : 'en';
	}

	/**
	 * HTML lang attribute (BCP 47-ish).
	 *
	 * @return string
	 */
	public static function html_lang() {
		$map = array(
			'en' => 'en',
			'zh' => 'zh-CN',
			'es' => 'es',
			'ar' => 'ar',
			'id' => 'id',
			'pt' => 'pt-BR',
			'fr' => 'fr',
			'ja' => 'ja',
			'ru' => 'ru',
			'de' => 'de',
		);
		$code = self::language();
		return isset( $map[ $code ] ) ? $map[ $code ] : 'en';
	}

	/**
	 * Whether current language is RTL.
	 *
	 * @return bool
	 */
	public static function is_rtl() {
		return 'ar' === self::language();
	}

	/**
	 * Translate a string key.
	 *
	 * @param string $key  String key.
	 * @param mixed  ...$args sprintf args.
	 * @return string
	 */
	public static function t( $key, ...$args ) {
		$catalog = self::catalog();
		$lang    = self::language();
		$text    = isset( $catalog[ $lang ][ $key ] )
			? $catalog[ $lang ][ $key ]
			: ( isset( $catalog['en'][ $key ] ) ? $catalog['en'][ $key ] : $key );

		if ( ! empty( $args ) ) {
			return vsprintf( $text, $args );
		}
		return $text;
	}

